export function getLocalizedAACTiles(lang?: LanguageCode): LocalizedAACDef[] {
  const dict = lang ? LOCALIZED_AAC_BY_LANG[lang] : undefined;
  return DEFAULT_AAC_EN.map((item) => {
    const trans = dict?.[item.id];
    return trans ? {...item, label: trans.label, phrase: trans.phrase} : item;
  });
}

